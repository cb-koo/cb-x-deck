// 2026-11-13에 원본 표에서 옮겼다. 일요일과 겹친 국경일은 목록에 있어도 영향이 없다(보내는 요일이 월수목금이라).
// 다음 해 목록은 해가 바뀌기 전에(보통 6월 말 발표) 추가한다. 선거일 같은 임시공휴일은 지정되면 한 줄 추가한다.
// 목록에 없는 해는 'unknown-year' — 부르는 쪽이 보내되 "목록 없음"을 남긴다.

const range = (from: string, to: string, name: string): Array<[string, string]> => {
  const out: Array<[string, string]> = [];
  for (let d = new Date(from + 'T00:00:00Z'); d <= new Date(to + 'T00:00:00Z'); d.setUTCDate(d.getUTCDate() + 1)) {
    out.push([d.toISOString().slice(0, 10), name]);
  }
  return out;
};

