-- 이슈 번호 — 보낸 순서대로 1, 2, 3… 이미 있는 줄에도 이 문장이 번호를 채운다.
alter table issue_report add column if not exists no bigint generated by default as identity;
create unique index if not exists issue_report_no_idx on issue_report (no);

-- 스크린샷 여러 장 — issue-screenshot 버킷 안 경로들(앞에서부터 붙인 순서)
alter table issue_report add column if not exists screenshot_paths text[] not null default '{}';

-- 1장 칸에만 있던 것(083 시절, 그리고 빌드 중 옛 코드가 쓴 것)을 옮긴다 — 이미 옮겼으면 건드리지 않는다
update issue_report set screenshot_paths = array[screenshot_path]
 where screenshot_path is not null and cardinality(screenshot_paths) = 0;
