// date: 한국 날짜 'YYYY-MM-DD'
export function holidayOn(date: string): { name: string } | null | 'unknown-year' {
  const year = HOLIDAYS[Number(date.slice(0, 4))];
  if (!year) return 'unknown-year';
  const name = year.get(date);
  return name ? { name } : null;
}
